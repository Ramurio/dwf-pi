import assert from 'node:assert/strict';
import { mkdtemp, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
// Optional browser QA; point DYNAMICWF_PLAYWRIGHT_MODULE to an installed Playwright module.
const modulePath = process.env.DYNAMICWF_PLAYWRIGHT_MODULE;
if (!modulePath) throw new Error("Set DYNAMICWF_PLAYWRIGHT_MODULE to an installed Playwright module");
const { chromium } = await import(modulePath);
import { RunStore } from '../src/run-store.js';
import { prepareExecutionPlan } from '../src/execution-plan.js';
import { startGraphServer } from '../src/graph-view/server.js';
const directory = await mkdtemp(join(tmpdir(), 'dynamicwf-bookmark-browser-'));
const filename = join(directory, 'state.sqlite');
const store = new RunStore(filename);
const plan = await prepareExecutionPlan({ schemaVersion: 1, id: 'browser-bookmark', name: 'Browser bookmark', revision: 1, entryGraph: 'main', graphs: { main: { entry: 'done', nodes: [{ id: 'done', kind: 'end', value: { op: 'literal', value: null } }], edges: [] } } }, { cwd: directory, availableModels: [] });
const add = (id: string) => store.create({ id, plan: { ...plan, workflow: { ...plan.workflow, name: id } }, input: null, cwd: directory });
add('run-browser-a'); add('run-browser-b');
let viewer = await startGraphServer(filename, undefined, 0, { stable: true });
const browser = await chromium.launch({ headless: true });
try {
  let page = await browser.newPage();
  const errors: string[] = [];
  page.on('pageerror', (error: Error) => errors.push(error.message));
  const url = viewer.url;
  const selected = async (id: string) => { await page.waitForFunction((id: string) => document.querySelector('#run-id')?.textContent === id && !document.querySelector<HTMLElement>('#workspace')?.hidden, id); assert.equal(new URL(page.url()).searchParams.get('run'), id); };
  await page.goto(url + '?run=run-browser-a'); await selected('run-browser-a');
  await page.locator('#runs button').filter({ hasText: 'run-browser-b' }).click(); await selected('run-browser-b');
  await page.goBack(); await selected('run-browser-a');
  await page.goForward(); await selected('run-browser-b');
  await page.reload(); await selected('run-browser-b');
  await page.locator('#pause').click();
  await page.waitForFunction(() => document.querySelector('#run-status')?.textContent?.toLowerCase().includes('пауз'));
  assert.equal(store.get('run-browser-b').status, 'paused');
  const before = store.events('run-browser-b');
  await viewer.close();
  viewer = await startGraphServer(filename, undefined, Number(new URL(url).port), { stable: true });
  await page.waitForEvent('load', { timeout: 15_000 }); await selected('run-browser-b');
  assert.deepEqual(store.events('run-browser-b'), before);
  add('run-browser-c');
  await page.locator('#runs button').filter({ hasText: 'run-browser-c' }).waitFor({ timeout: 12_000 });
  await page.close(); page = await browser.newPage();
  await page.goto(url + '?run=run-browser-a'); await selected('run-browser-a');
  await page.goto(url + '?run=run-missing');
  await page.locator('#notice').waitFor({ state: 'visible' });
  assert.equal(new URL(page.url()).searchParams.get('run'), 'run-missing');
  assert.equal(await page.locator('#workspace').isVisible(), false);
  assert.deepEqual(errors, []);
  console.log('PASS: deep links, back/forward, reload, real pause, server restart, new run discovery, reopening tab, missing run.');
} finally { await browser.close(); await viewer.close(); store.close(); await rm(directory, { recursive: true, force: true }); }
