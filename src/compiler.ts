import { createHash } from "node:crypto";
import { parseWorkflow, type Graph, type Node, type WorkflowDefinition } from "./graph.js";

export const compilerVersion = "dynamicwf-effect-v1";
export interface CompiledWorkflow {
  readonly source: string;
  /** SHA-256 of generated UTF-8 source, including compiler version. */
  readonly hash: string;
  readonly workflow: WorkflowDefinition;
  readonly compilerVersion: typeof compilerVersion;
}

function canonical(value: unknown): string {
  if (value === null || typeof value !== "object") return JSON.stringify(value);
  if (Array.isArray(value)) return `[${value.map(canonical).join(",")}]`;
  return `{${Object.keys(value).sort().map((key) => `${JSON.stringify(key)}:${canonical((value as Record<string, unknown>)[key])}`).join(",")}}`;
}
// Parse a quoted JSON string instead of emitting object literals: __proto__ remains a data key.
function data(value: unknown): string { return `JSON.parse(${JSON.stringify(canonical(value))})`; }
function quote(value: string): string { return JSON.stringify(value); }

/** Compile validated graph structure into TypeScript + Effect control flow, without evaluating author text. */
export function compileWorkflow(value: unknown): CompiledWorkflow {
  const workflow = parseWorkflow(value);
  const graphIds = Object.keys(workflow.graphs).sort();
  const names = new Map(graphIds.map((id, index) => [id, `graph_${index}`]));
  const fn = (id: string): string => {
    const name = names.get(id);
    if (!name) throw new Error(`Compiler invariant: missing graph ${id}`);
    return name;
  };
  const body = graphIds.map((id) => emitGraph(id, workflow.graphs[id]!, fn)).join("\n\n");
  const source = `// Generated by ${compilerVersion}. Edit the workflow definition, not this module.
import { Effect } from "effect";
import { evaluate, chooseEdge } from "dynamicwf-pi/expressions";
import type { Json, Node, Edge } from "dynamicwf-pi/graph";
import type { RuntimeContext, WorkflowRuntime } from "dynamicwf-pi/runtime-contract";

export const metadata = ${data({ id: workflow.id, name: workflow.name, revision: workflow.revision, entryGraph: workflow.entryGraph, compilerVersion })};
const attempt = <A>(work: () => A): Effect.Effect<A, Error> => Effect.try({ try: work, catch: (error) => error instanceof Error ? error : new Error(String(error)) });

${body}

export function run(runtime: WorkflowRuntime, input: Json): Effect.Effect<Json, Error> {
  return ${fn(workflow.entryGraph)}(runtime, input, ["graph", ${quote(workflow.entryGraph)}]);
}
`;
  return Object.freeze({ source, hash: createHash("sha256").update(source, "utf8").digest("hex"), workflow, compilerVersion });
}

function emitGraph(graphId: string, graph: Graph, fn: (id: string) => string): string {
  return `function ${fn(graphId)}(runtime: WorkflowRuntime, input: Json, scope: readonly string[]): Effect.Effect<Json, Error> {
  return Effect.gen(function* () {
    const nodes: Record<string, Json> = Object.create(null);
    const visits: Record<string, number> = Object.create(null);
    const edges: Edge[] = ${data(graph.edges)};
    let pc: string = ${quote(graph.entry)};
    while (true) {
      switch (pc) {
${graph.nodes.map((node) => emitNode(graphId, node, fn)).join("\n")}
        default: return yield* Effect.fail(new Error("Unknown generated program counter: " + pc));
      }
    }
  });
}`;
}

function emitNode(graphId: string, node: Node, fn: (id: string) => string): string {
  let work: string;
  switch (node.kind) {
    case "agent": work = `const task = yield* attempt(() => evaluate(node.task, { input, nodes }));
            if (typeof task !== "string") return yield* Effect.fail(new Error("Agent task must evaluate to a string"));
            const value = yield* attempt(() => node.input === undefined ? structuredClone(input) : evaluate(node.input, { input, nodes }));
            return yield* runtime.agent(context, node, task, value);`; break;
    case "worktree": work = `const childInput = yield* attempt(() => evaluate(node.input, { input, nodes }));
            return yield* runtime.worktree(context, node, childScope => ${fn(node.graphId)}(runtime, childInput, childScope));`; break;
    case "integrate": work = `const sources = yield* attempt(() => evaluate(node.sources, { input, nodes }));
            return yield* runtime.integrate(context, node, sources);`; break;
    case "check": work = "return yield* runtime.check(context, node);"; break;
    case "transform": case "end": work = "return yield* attempt(() => evaluate(node.value, { input, nodes }));"; break;
    case "branch": work = "return yield* attempt(() => node.input === undefined ? structuredClone(input) : evaluate(node.input, { input, nodes }));"; break;
    case "subworkflow": work = `const childInput = yield* attempt(() => evaluate(node.input, { input, nodes }));
            return yield* ${fn(node.graphId)}(runtime, childInput, [...scope, "node", node.id, "visit", String(visit), "subworkflow", "graph", ${quote(node.graphId)}]);`; break;
    case "map": work = `const items = yield* attempt(() => {
              const value = evaluate(node.items, { input, nodes });
              if (!Array.isArray(value)) throw new Error("Map items must evaluate to an array");
              return value;
            });
            return yield* Effect.forEach(items, (item, index) => ${fn(node.graphId)}(runtime, item, [...scope, "node", node.id, "visit", String(visit), "map", String(index), "graph", ${quote(node.graphId)}]), { concurrency: ${node.concurrency ?? '"unbounded"'} });`; break;
    case "parallel": work = `const results = yield* Effect.forEach([
${node.children.map((child, index) => `              () => Effect.gen(function* () {
                const child = node.children[${index}]!;
                const childInput = yield* attempt(() => evaluate(child.input, { input, nodes }));
                const result = yield* ${fn(child.graphId)}(runtime, childInput, [...scope, "node", node.id, "visit", String(visit), "parallel", child.id, "graph", ${quote(child.graphId)}]);
                return [child.id, result] as const;
              })`).join(",\n")}
            ], (child) => child(), { concurrency: ${node.concurrency ?? '"unbounded"'} });
            return Object.fromEntries(results);`; break;
  }
  return `        case ${quote(node.id)}: {
          const node = ${data(node)} as Node & { kind: ${quote(node.kind)} };
          const visit = visits[node.id] ?? 0;
          visits[node.id] = visit + 1;
          const context: RuntimeContext = { graphId: ${quote(graphId)}, nodeId: node.id, scope: [...scope], visit };
          const result = yield* runtime.step(context, () => Effect.gen(function* () {
            ${work}
          }));
          nodes[node.id] = result;
          ${node.kind === "end" ? "return result;" : 'pc = yield* attempt(() => chooseEdge(node.id, edges, { input, nodes }));\n          break;'}
        }`;
}
